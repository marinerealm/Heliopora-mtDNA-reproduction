"""STEP 5 - Collect the key numbers into results/SUMMARY.md and all tables into results/all_results.xlsx.
Labels in the result tables follow the sample sheets; this summary uses the manuscript names:
lineage A = subclade sp.3, A' = sp.2, B = coe.3; 'reproductive' = during brooding."""
import pandas as pd
from qpcr_lib import RES

E = pd.read_csv(RES / "01_expression_main.csv")
T = pd.read_csv(RES / "03_mtdna_tests.csv")
V = pd.read_csv(RES / "02_estimator_validation.csv")
K = pd.read_csv(RES / "04_replicate_summary.csv")
f = lambda x, d=3: f"{x:.{d}f}"
ANALYSIS = {"B2014 reproductive vs before": "coe.3 2014: during vs before brooding",
            "B2014 KR vs YIS difference in change": "coe.3 2014: KR vs YIS difference in change",
            "B2014 baseline sites (13 Jul)": "coe.3 2014: sites before brooding (13 Jul)",
            "Yonara 2017 lineages": "Yonara 2017 subclades",
            "Yonara 2017 lineages (Tukey HSD)": "Yonara 2017 subclades (Tukey HSD)"}
CONTRAST = {"A - B": "sp.3 - coe.3", "A' - B": "sp.2 - coe.3", "A - A'": "sp.3 - sp.2",
            "A = A' = B (one-way ANOVA)": "sp.3 = sp.2 = coe.3 (one-way ANOVA)"}
MEASURE = {"mtCN": "copy number (SRP54), log2", "COIs_per_input": "copy number (per DNA input), log2",
           "lesions_poisson": "lesions per 10 kb (Poisson)", "lesions_rothfuss": "lesions per 10 kb (Rothfuss)"}
L = ["# Key results (regenerated by run_all.py)", "",
     "## Gene expression, KR, during vs before brooding (n = 3 v 3; Student t, df = 4; q = BH over 9 targets)", "",
     "| Gene | Fold change | 95% CI | p | q |", "|---|---|---|---|---|"]
for _, r in E[E.role == "target"].iterrows():
    L.append(f"| {r.gene} | {f(r.FC, 2)} | {f(r.FC_CI_lo, 2)}-{f(r.FC_CI_hi, 2)} | {f(r.p)} | {f(r.q_BH, 2)} |")
L += ["", "## mtDNA (Welch t within site; Tukey HSD for subclades)", "", "| Analysis | Contrast | Measure | n | Difference | p |", "|---|---|---|---|---|---|"]
for _, r in T[T.measure.isin(list(MEASURE))].iterrows():
    L.append(f"| {ANALYSIS.get(r.analysis, r.analysis)} | {CONTRAST.get(r.contrast, r.contrast)} | {MEASURE[r.measure]} | {r.n} | "
             f"{'' if pd.isna(r['diff']) else f(r['diff'], 2)} | {f(r.p)} |")
L += ["", "Copy-number differences are in log2 units; lesions are per 10 kb.", "",
      "## Independent KR replicate run (14 Mar 2018)", "", "| Quantity | Method | Change | p |", "|---|---|---|---|"]
for _, r in K.iterrows():
    L.append(f"| {r.quantity} | {r.method} | {f(r.log2_change, 2)} | {f(r.p_welch)} |")
L += ["", "## Estimator validation against LinRegPCR 2017.1", "", V.round(3).to_markdown(index=False)]
(RES / "SUMMARY.md").write_text("\n".join(L) + "\n", encoding="utf-8")
with pd.ExcelWriter(RES / "all_results.xlsx") as w:
    for p in sorted(RES.glob("0*.csv")):
        pd.read_csv(p).to_excel(w, sheet_name=p.stem[:31], index=False)
print("STEP 5 done: results/SUMMARY.md and results/all_results.xlsx")
